-- 验证：查看生成数据统计
-- ============================================================
SELECT '订单总数' AS 项目, COUNT(*) AS 数量 FROM `orders`
UNION ALL
SELECT '已出库(COMPLETED)', COUNT(*) FROM `orders` WHERE `status` = 'COMPLETED'
UNION ALL
SELECT '待出库(PENDING)', COUNT(*) FROM `orders` WHERE `status` = 'PENDING'
UNION ALL
SELECT '已退货(CANCELLED)', COUNT(*) FROM `orders` WHERE `status` = 'CANCELLED'
UNION ALL
SELECT '订单项总数', COUNT(*) FROM `order_item`
UNION ALL
SELECT '超库存订单数', COUNT(DISTINCT o.id) FROM `orders` o JOIN `order_item` oi ON o.id = oi.order_id JOIN `product` p ON oi.product_id = p.id WHERE oi.quantity > p.stock;
